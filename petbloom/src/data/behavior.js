/** 取某物种可用的行为图鉴键（爬宠共用一套）。 */
export function signalKeyFor(speciesId) {
  if (['lizard', 'turtle', 'snake'].includes(speciesId)) return 'reptile';
  if (['guineaPig', 'chinchilla', 'hamster'].includes(speciesId)) return 'rabbit';
  return speciesId;
}
