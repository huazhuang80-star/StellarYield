/** 评估题：0-10 分表示对该信念的相信程度。 */
export const ASSESSMENT_SCALE = { min: 0, max: 10, step: 1, labels: { 0: '完全不认同', 5: '有点认同', 10: '非常认同' } };

/**
 * 按得分排出修补优先级（分数越高优先级越高）。
 * @param {object} scores {mythId: number}
 */
export function prioritizeMyths(scores = {}) {
  return MYTHS.map((m) => ({ myth: m, score: Number(scores[m.id]) || 0 }))
    .sort((a, b) => b.score - a.score)
    .filter((x) => x.score > 0);
}
