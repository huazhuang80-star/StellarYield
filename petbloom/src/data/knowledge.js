/** 按当前物种过滤（'all' 与包含该物种的都保留）。 */
export function articlesFor(speciesId) {
  return ARTICLES.filter((a) => a.species === 'all' || (Array.isArray(a.species) && a.species.includes(speciesId)));
}

export function articleById(id) {
  return ARTICLES.find((a) => a.id === id) ?? null;
}
